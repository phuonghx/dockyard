#!/usr/bin/env python3
"""Compile po/*.po into package/contents/ui/translations.js (used by L10n.qml).

The widget picks its language at run time (system language or the user's choice), which gettext
cannot do inside a Plasma widget, so the catalogues are also shipped as one small JS table.
Keys are "<msgctxt>\\n<msgid>" and values are the list of plural forms. Fuzzy/empty entries are skipped.
"""
import glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "package/contents/ui/translations.js")


def unquote(lines):
    return "".join(json.loads(l) for l in lines)


def parse(path):
    entries, cur, field, fuzzy = {}, {}, None, False
    def flush():
        nonlocal cur, fuzzy
        if cur.get("msgid") and not fuzzy:
            forms = [cur[k] for k in sorted((k for k in cur if k.startswith("msgstr")), key=lambda k: (len(k), k))]
            forms = [unquote(f) for f in forms]
            if forms and all(forms):
                entries[(unquote(cur.get("msgctxt", [])) + "\n") + unquote(cur["msgid"])] = forms
        cur, fuzzy = {}, False
    for raw in open(path, encoding="utf-8").read().split("\n"):
        line = raw.strip()
        if not line:
            flush(); field = None; continue
        if line.startswith("#"):
            if line.startswith("#,") and "fuzzy" in line: fuzzy = True
            continue
        m = re.match(r'^(msgctxt|msgid_plural|msgid|msgstr(?:\[\d+\])?)\s+(".*")$', line)
        if m:
            field = m.group(1); cur[field] = [m.group(2)]
        elif line.startswith('"') and field:
            cur[field].append(line)
    flush()
    entries.pop("\n", None)  # the header
    return entries


def main():
    data = {}
    for po in sorted(glob.glob(os.path.join(ROOT, "po", "*.po"))):
        data[os.path.basename(po)[:-3]] = parse(po)
    body = json.dumps(data, ensure_ascii=False, indent=0, sort_keys=True)
    out = ".pragma library\n// Generated by tools/po2js.py from po/*.po. Do not edit.\nvar data = " + body + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == out
        print("translations.js is up to date" if ok else "translations.js is OUT OF DATE: run tools/i18n.sh compile")
        sys.exit(0 if ok else 1)
    open(OUT, "w", encoding="utf-8").write(out)
    print("wrote", os.path.relpath(OUT, ROOT), "-", {k: len(v) for k, v in data.items()})


main()
